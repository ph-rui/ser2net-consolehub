<#
    package-deploy.ps1 - build a clean deployable package for a SECOND Windows box.

    Usage:  powershell -ExecutionPolicy Bypass -File .\package-deploy.ps1 [-TargetIp 10.0.9.2]
                                     (default TargetIp = 10.0.9.2)

    Output: <root>\deploy\ser2net-deploy-<yyyyMMdd-HHmm>.zip

    What it ships (self-contained, runs anywhere):
      bin\ser2net.exe + all DLLs + every .ps1 (all scripts are $PSScriptRoot-relative)
      etc\ser2net\ser2net.template.yaml
      linux\console.sh / ptybridge.py / selftest.py
      settings.json (bindIp pre-set to -TargetIp)
      README.md + DEPLOY-NEW-BOX.md

    What it deliberately EXCLUDES (target-machine runtime state that must be
    rebuilt on the new box - copying it would import THIS box's hardware):
      devices.json          <- fingerprints of this box's USB hardware
      ports.json            <- port assignment table
      ser2net.pid           <- this box's running process id
      restart.request       <- pending restart marker
      logs\                 <- runtime logs
      etc\ser2net\ser2net.yaml      <- regenerated by render on first start
      linux\t-*.py                  <- dev/test scripts
#>
[CmdletBinding()]
param(
    [string] $TargetIp = '10.0.9.2'
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$DeployDir = Join-Path $Root 'deploy'
$Stamp = Get-Date -Format 'yyyyMMdd-HHmm'
$Stage = Join-Path $DeployDir "stage-$Stamp"
$Zip   = Join-Path $DeployDir "ser2net-deploy-$Stamp.zip"

New-Item -ItemType Directory -Force -Path (Join-Path $Stage 'bin')        | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $Stage 'etc\ser2net')| Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $Stage 'linux')      | Out-Null

# ---- bin\ : ser2net.exe + DLLs + all scripts (nothing machine-specific now) ---
Copy-Item (Join-Path $Root 'bin\*') (Join-Path $Stage 'bin\') -Recurse -Force

# ---- etc\ser2net\ : template only (yaml regenerated by render) ----------------
Copy-Item (Join-Path $Root 'etc\ser2net\ser2net.template.yaml') (Join-Path $Stage 'etc\ser2net\') -Force

# ---- linux\ : the 3 shipped files -------------------------------------------------
foreach ($f in 'console.sh', 'ptybridge.py', 'selftest.py') {
    Copy-Item (Join-Path $Root "linux\$f") (Join-Path $Stage 'linux\') -Force
}

# ---- root files --------------------------------------------------------------------
foreach ($f in 'settings.json', 'README.md', 'DEPLOY-NEW-BOX.md') {
    $p = Join-Path $Root $f
    if (Test-Path $p) { Copy-Item $p $Stage -Force }
}

# ---- sanitize the settings copy (text-level replaces keep the file's formatting) ---
$s = Join-Path $Stage 'settings.json'
$txt = Get-Content -Raw -Encoding UTF8 $s
$txt = $txt -replace '"bindIp":\s*"[^"]*"', ('"bindIp":  "' + $TargetIp + '"')
$txt = $txt -replace '"sudoPassword":\s*"[^"]*"', '"sudoPassword":  "EDIT-ME"'
[System.IO.File]::WriteAllText($s, $txt, (New-Object System.Text.UTF8Encoding($false)))

# ---- zip it --------------------------------------------------------------------------
if (Test-Path $Zip) { Remove-Item $Zip -Force }
Compress-Archive -Path (Join-Path $Stage '*') -DestinationPath $Zip -CompressionLevel Optimal
Remove-Item $Stage -Recurse -Force

Write-Host ''
Write-Host "package ready:  $Zip" -ForegroundColor Green
Write-Host "  settings.json inside: bindIp=$TargetIp"
Write-Host ''
Write-Host 'contents:'
Add-Type -AssemblyName System.IO.Compression.FileSystem
$z = [System.IO.Compression.ZipFile]::OpenRead($Zip)
$z.Entries | ForEach-Object { $_.FullName } | Sort-Object | ForEach-Object { '  ' + $_ }
$z.Dispose()