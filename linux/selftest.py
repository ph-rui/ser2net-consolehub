#!/usr/bin/env python3
"""
selftest.py - validate a ser2net console link without touching the board.

Three phases, each independently useful:

  1. LINK      TCP connect + read the ser2net banner.
               Proves ser2net is listening and the port maps to the right slot.
               Works even if the board is powered off.

  2. ALIVE     Send CRLF and see whether anything comes back.
               Distinguishes "board is dead / wrong baud" from
               "network path is broken".

  3. ECHO      If the console echoes (it usually does), send N random tokens
               and confirm each one returns intact, measuring latency.
               Catches byte corruption and gross latency.

Usage:
    ./selftest.py              # every device in devices.conf (or legacy slots a-d)
    ./selftest.py a            # by alias
    ./selftest.py imx95        # by label (substring, case-insensitive)
    ./selftest.py 4002         # by port number
    ./selftest.py --host 172.16.66.163 --timeout 6

The device table is read from ./devices.conf (DEVICES_CONF to override),
the same file console.sh uses - regenerate it on Windows with
`serial-hub.ps1 render` and copy it over when it changes.
"""

import argparse
import os
import random
import socket
import statistics
import string
import sys
import time

DEFAULT_HOST = os.environ.get("HOST", "172.16.66.163")
DEFAULT_PORTS = {
    "a": int(os.environ.get("PORT_A", 4000)),
    "b": int(os.environ.get("PORT_B", 4001)),
    "c": int(os.environ.get("PORT_C", 4002)),
    "d": int(os.environ.get("PORT_D", 4003)),
}
DEVICES_CONF = os.environ.get(
    "DEVICES_CONF", os.path.join(os.path.dirname(os.path.abspath(__file__)), "devices.conf")
)


def load_conf(path):
    """Parse the devices.conf generated by serial-hub.ps1 render.

    Returns a list of {alias, host, port, label} or None if unreadable.
    Format per line:  alias  label...  host  port   (label may contain spaces)
    """
    entries = []
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for raw in fh:
                line = raw.rstrip()
                if not line or line.startswith("#"):
                    continue
                parts = line.split()
                if len(parts) < 3:
                    continue
                entries.append({
                    "alias": parts[0],
                    "host": parts[-2],
                    "port": int(parts[-1]),
                    "label": " ".join(parts[1:-2]),
                })
    except OSError:
        return None
    return entries


def c(text, code):
    return f"\033[{code}m{text}\033[0m"


def drain(sock, settle=0.35, hard_cap=2.0):
    """Read whatever arrives within a short settle window."""
    out = bytearray()
    deadline = time.time() + hard_cap
    sock.settimeout(settle)
    while time.time() < deadline:
        try:
            chunk = sock.recv(4096)
            if not chunk:
                break
            out += chunk
            sock.settimeout(settle)
        except socket.timeout:
            break
        except OSError:
            break
    return bytes(out)


def read_until(sock, needle, timeout):
    """Read until `needle` appears or timeout expires."""
    buf = bytearray()
    deadline = time.time() + timeout
    sock.settimeout(0.2)
    while time.time() < deadline:
        try:
            chunk = sock.recv(4096)
            if not chunk:
                break
            buf += chunk
            if needle in bytes(buf):
                return bytes(buf), True
        except socket.timeout:
            continue
        except OSError:
            break
    return bytes(buf), False


def test_slot(host, port, rounds, timeout, name=""):
    label = name or f"port {port}"
    result = {"host": host, "port": port, "link": False, "alive": False,
              "echo": None, "latency_ms": [], "detail": "", "label": label}

    # ---- phase 1: LINK -------------------------------------------------
    try:
        sock = socket.create_connection((host, port), timeout=timeout)
    except OSError as exc:
        result["detail"] = f"TCP connect failed: {exc}"
        return result
    result["link"] = True

    banner, got = read_until(sock, b"\n", timeout=min(timeout, 3.0))
    result["banner"] = banner.decode("ascii", "replace").strip()

    # ser2net also echoes back the CRLF we send, so clear the line discipline
    # before the echo test.
    try:
        sock.sendall(b"\r\n")
    except OSError:
        pass
    drain(sock, settle=0.4)

    # ---- phase 2: ALIVE ------------------------------------------------
    quiet = drain(sock, settle=1.0, hard_cap=timeout)
    result["alive"] = len(quiet) > 0
    result["alive_bytes"] = len(quiet)
    result["alive_sample"] = quiet[:160].decode("ascii", "replace")

    # ---- phase 3: ECHO -------------------------------------------------
    if result["alive"]:
        latencies = []
        corrupt = 0
        alphabet = string.ascii_letters + string.digits
        try:
            for _ in range(max(1, rounds)):
                token = "".join(random.choice(alphabet) for _ in range(12))
                t0 = time.perf_counter()
                sock.sendall(token.encode() + b"\r\n")
                _, hit = read_until(sock, token.encode(), timeout=min(timeout, 4.0))
                dt = (time.perf_counter() - t0) * 1000.0
                if hit:
                    latencies.append(dt)
                else:
                    corrupt += 1
                drain(sock, settle=0.12)
        except OSError as exc:
            result["detail"] = f"socket error during echo: {exc}"

        result["echo"] = {"rounds": max(1, rounds), "returned": len(latencies),
                          "lost": corrupt, "corrupt": 0}
        if latencies:
            result["latency_ms"] = latencies
    else:
        result["echo"] = {"rounds": 0, "returned": 0, "lost": 0,
                          "skipped": "board produced no output"}

    try:
        sock.close()
    except OSError:
        pass
    return result


def report(r):
    lines = []
    head = f"{r['label']}  ({r['host']}:{r['port']})"
    if not r["link"]:
        lines.append(c(f"  {head:<22} LINK FAIL", 31) + "  " + r["detail"])
        return lines

    lines.append(c(f"  {head:<22} LINK ok", 32)
                 + f"  banner: {r.get('banner', '')[:70]!r}")

    if r["alive"]:
        lines.append(c(f"  {'':<22} ALIVE ok", 32)
                     + f"  {r['alive_bytes']} bytes back: "
                       + repr(r["alive_sample"][:60]))
    else:
        lines.append(c(f"  {'':<22} ALIVE no-data", 33)
                     + "  board silent - check power, wiring, and baud rate")

    e = r["echo"]
    if e["rounds"] == 0:
        lines.append(c(f"  {'':<22} ECHO skipped", 33)
                     + "  " + e.get("skipped", ""))
    elif e["returned"] == 0:
        lines.append(c(f"  {'':<22} ECHO 0/{e['rounds']} returned", 31)
                     + "  link carries bytes but the console does not echo")
    else:
        colour = 32 if e["lost"] == 0 else 31
        lines.append(c(f"  {'':<22} ECHO {e['returned']}/{e['rounds']} intact", colour)
                     + (f"  lost={e['lost']}" if e["lost"] else ""))
        lat = r["latency_ms"]
        if lat:
            lines.append(f"  {'':<22} latency  "
                         + f"min={min(lat):.1f}ms  med={statistics.median(lat):.1f}ms  "
                         + f"max={max(lat):.1f}ms")
    return lines


def main():
    ap = argparse.ArgumentParser(description="ser2net console link self-test")
    ap.add_argument("target", nargs="?", help="device alias / label / port number (see devices.conf)")
    ap.add_argument("--host", default=DEFAULT_HOST)
    ap.add_argument("--rounds", type=int, default=8)
    ap.add_argument("--timeout", type=float, default=4.0)
    args = ap.parse_args()

    entries = load_conf(DEVICES_CONF)
    host_from_conf = "--host" not in sys.argv and entries is not None

    # targets: list of {host, port, name}
    if args.target:
        if args.target.isdigit():
            targets = [{"host": args.host, "port": int(args.target), "name": ""}]
        elif entries is not None:
            key = args.target.lower()
            hit = next((e for e in entries if e["alias"].lower() == key), None)
            if hit is None:
                hit = next((e for e in entries if key in e["label"].lower()), None)
            if hit is None:
                ap.error(f"unknown device '{args.target}' (use an alias, a label, or a port)")
            targets = [{"host": hit["host"] if host_from_conf else args.host,
                        "port": hit["port"],
                        "name": f"{hit['alias']} {hit['label']}".strip()}]
        else:
            key = args.target.lower()
            if key not in DEFAULT_PORTS:
                ap.error(f"unknown slot '{args.target}' (use a|b|c|d or a port)")
            targets = [{"host": args.host, "port": DEFAULT_PORTS[key], "name": key}]
    elif entries is not None:
        targets = [{"host": e["host"] if host_from_conf else args.host,
                    "port": e["port"],
                    "name": f"{e['alias']} {e['label']}".strip()}
                   for e in entries]
    else:
        targets = [{"host": args.host, "port": p, "name": s}
                   for s, p in DEFAULT_PORTS.items()]

    print(c(f"ser2net console self-test  host={args.host}  "
            f"targets={[t['port'] for t in targets]}", 1))
    print()

    results = []
    for t in targets:
        r = test_slot(t["host"], t["port"], args.rounds, args.timeout, t["name"])
        results.append(r)
        for line in report(r):
            print(line)
        print()

    linked = sum(1 for r in results if r["link"])
    alive = sum(1 for r in results if r["alive"])
    clean = sum(1 for r in results
                if r["echo"] and r["echo"]["rounds"] and r["echo"]["lost"] == 0)

    print(f"summary: {linked}/{len(results)} linked, "
          f"{alive}/{len(results)} board-alive, "
          f"{clean}/{len(results)} echo-clean")

    if linked == 0:
        print(c("\nAll links failed. On the Windows host run:", 31))
        print("    bin\\serial-hub.ps1 status")
        print("    bin\\serial-hub.ps1 doctor")
        print("A device with no board attached renders as 'enable: off' and will")
        print("not listen at all - that is the most common cause.", 31)
        return 2
    return 0 if alive == 0 or clean == alive else 1


if __name__ == "__main__":
    sys.exit(main())
